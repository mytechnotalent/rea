/// Renders a document as a complete Typst source file.
///
/// # Arguments
///
/// * `doc` - Document to render.
///
/// # Returns
///
/// Typst markup ready for compilation.
#[must_use]
pub fn render(doc: &Document) -> String {
    let (title, subtitle) = (string(&doc.title), string(&doc.subtitle));
    let head = format!("#set document(title: {title})\n#cover({title}, {subtitle})\n");
    let mut out = PREAMBLE.to_string() + &head;
    for section in &doc.sections {
        out.push_str(&section_markup(section));
    }
    out
}

/// Renders one section as a level-one heading followed by its blocks.
///
/// # Arguments
///
/// * `section` - Section to render.
///
/// # Returns
///
/// Typst markup for the section.
fn section_markup(section: &Section) -> String {
    let mut out = format!("= {}\n\n", rich(&section.heading));
    for block in &section.blocks {
        out.push_str(&block_markup(block));
        out.push('\n');
    }
    out
}

/// Renders one block.
///
/// # Arguments
///
/// * `block` - Block to render.
///
/// # Returns
///
/// Typst markup for the block, ending in a newline.
fn block_markup(block: &Block) -> String {
    match block {
        Block::Paragraph(t) => format!("{}\n", rich(t)),
        Block::Bullets(items) => items.iter().map(|i| bullet(i)).collect(),
        Block::Table(table) => table_markup(table),
        Block::Code(code) => format!("#raw(block: true, {})\n", string(code)),
        Block::Subheading(t) => format!("== {}\n", rich(t)),
    }
}

/// Renders one bullet list item.
///
/// # Arguments
///
/// * `item` - Item text.
///
/// # Returns
///
/// A Typst list line.
fn bullet(item: &str) -> String {
    format!("- {}\n", rich(item))
}

/// Renders a table with a repeating header row.
///
/// # Arguments
///
/// * `table` - Table to render.
///
/// # Returns
///
/// A Typst `table` call.
fn table_markup(table: &Table) -> String {
    let header: Vec<String> = table.headers.iter().map(|h| cell(h)).collect();
    let body: Vec<String> = table.rows.iter().flatten().map(|c| cell(c)).collect();
    let columns = column_spec(table.headers.len());
    let header = header.join(", ");
    let body = body.join(", ");
    format!("#table(columns: {columns}, table.header({header}), {body})\n")
}

/// Builds a column specification that lets long cells wrap.
///
/// The first and last columns size to content; interior columns flex.
///
/// # Arguments
///
/// * `count` - Column count.
///
/// # Returns
///
/// The Typst columns argument.
fn column_spec(count: usize) -> String {
    match count {
        0 | 1 => "auto".to_string(),
        2 => "(auto, 1fr)".to_string(),
        other => format!("(auto, {}auto)", "1fr, ".repeat(other - 2)),
    }
}

/// Wraps text as one table cell.
///
/// # Arguments
///
/// * `raw` - Cell text.
///
/// # Returns
///
/// A Typst content block holding the text.
fn cell(raw: &str) -> String {
    format!("[{}]", rich(&breakable(raw)))
}

/// Inserts zero-width break opportunities into long runs.
///
/// Long unbreakable tokens such as hashes and JSON would otherwise overflow
/// their table cell and overlap the adjacent column.
///
/// # Arguments
///
/// * `text` - Cell text.
///
/// # Returns
///
/// The text with zero-width spaces injected every 16 characters per run.
fn breakable(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + text.len() / 16 + 8);
    let mut run = 0;
    for c in text.chars() {
        step_break(&mut out, &mut run, c);
    }
    out
}

/// Advances a run counter and injects a break at the interval.
///
/// # Arguments
///
/// * `out` - Destination buffer.
/// * `run` - Current run length.
/// * `c` - Current character.
fn step_break(out: &mut String, run: &mut usize, c: char) {
    if c.is_whitespace() {
        *run = 0;
    } else {
        *run += 1;
        insert_break(out, *run);
    }
    out.push(c);
}

/// Pushes a zero-width space at the break interval.
///
/// # Arguments
///
/// * `out` - Destination buffer.
/// * `run` - Current run length.
fn insert_break(out: &mut String, run: usize) {
    if run.is_multiple_of(16) {
        out.push('\u{200b}');
    }
}

/// Finds the opening and closing tag offsets.
///
/// # Arguments
///
/// * `s` - Source text.
/// * `tag` - Tag delimiter.
///
/// # Returns
///
/// Text before the tag, inner content, and remainder.
fn find_tag<'a>(s: &'a str, tag: &str) -> Option<(&'a str, &'a str, &'a str)> {
    let open = s.find(tag)?;
    let rest = &s[open + tag.len()..];
    let close = rest.find(tag)?;
    let (before, inner) = (&s[..open], &rest[..close]);
    let after = &rest[close + tag.len()..];
    Some((before, inner, after))
}

/// Parses a bold markdown token.
///
/// # Arguments
///
/// * `s` - Source text.
///
/// # Returns
///
/// Text before, Typst strong markup, and remainder.
fn parse_bold(s: &str) -> Option<(&str, String, &str)> {
    let (before, inner, after) = find_tag(s, "**")?;
    Some((before, format!("#strong[{}]", rich(inner)), after))
}

/// Parses an inline code markdown token.
///
/// # Arguments
///
/// * `s` - Source text.
///
/// # Returns
///
/// Text before, Typst raw markup, and remainder.
fn parse_raw(s: &str) -> Option<(&str, String, &str)> {
    let (before, inner, after) = find_tag(s, "`")?;
    Some((before, ["#raw(", &string(inner), ")"].concat(), after))
}

/// Finds the earliest inline token in text.
///
/// # Arguments
///
/// * `s` - Source text.
///
/// # Returns
///
/// Text before, formatted token, and remainder.
fn next_token(s: &str) -> Option<(&str, String, &str)> {
    match (parse_bold(s), parse_raw(s)) {
        (Some(b), Some(r)) if b.0.len() <= r.0.len() => Some(b),
        (Some(_) | None, Some(r)) => Some(r),
        (Some(b), None) => Some(b),
        (None, None) => None,
    }
}

/// Appends text as a Typst text call when non-empty.
///
/// # Arguments
///
/// * `out` - Destination buffer.
/// * `t` - Text slice.
fn push_text(out: &mut String, t: &str) {
    if !t.is_empty() {
        out.push_str("#text(");
        out.push_str(&string(t));
        out.push(')');
    }
}

/// Converts markdown-style inline formatting to Typst elements.
///
/// # Arguments
///
/// * `s` - Text containing markdown bold or code.
///
/// # Returns
///
/// Typst element markup.
fn rich(mut s: &str) -> String {
    let mut out = String::new();
    while let Some((before, token, after)) = next_token(s) {
        push_text(&mut out, before);
        out.push_str(&token);
        s = after;
    }
    push_text(&mut out, s);
    out
}

/// Quotes text as a Typst string literal.
///
/// # Arguments
///
/// * `raw` - Untrusted text.
///
/// # Returns
///
/// A double-quoted literal with every special character escaped.
fn string(raw: &str) -> String {
    let body: String = raw.chars().map(escape).collect();
    format!("\"{body}\"")
}

/// Escapes one character for use inside a Typst string literal.
///
/// # Arguments
///
/// * `c` - Character to escape.
///
/// # Returns
///
/// The character itself or its escape sequence.
fn escape(c: char) -> String {
    match c {
        '\\' => "\\\\".to_string(),
        '"' => "\\\"".to_string(),
        '\n' => "\\n".to_string(),
        c if c.is_control() => format!("\\u{{{:x}}}", u32::from(c)),
        c => c.to_string(),
    }
}

#[cfg(test)]
mod tests {
    // Import all parent module items
    use super::*;

    /// Verifies that quotes, backslashes, and controls are escaped.
    #[test]
    fn test_string_escapes_specials() {
        assert_eq!(string("a\"b\\c\n\u{1}"), "\"a\\\"b\\\\c\\n\\u{1}\"");
    }

    /// Verifies that markup characters are inert inside rich text.
    #[test]
    fn test_rich_wraps_markup_characters() {
        assert_eq!(rich("*_#$"), "#text(\"*_#$\")");
    }

    /// Verifies that bold and code are converted to Typst functions.
    #[test]
    fn test_rich_formats_bold_and_code() {
        let got = rich("**bold** and `code`");
        assert_eq!(
            got,
            "#strong[#text(\"bold\")]#text(\" and \")#raw(\"code\")"
        );
    }

    /// Verifies table markup carries the column count and cells.
    #[test]
    fn test_table_markup_lists_cells() {
        let table = Table::new(&["A", "B"]).row(vec!["1".into(), "2".into()]);
        let want = "#table(columns: (auto, 1fr), table.header([#text(\"A\")], [#text(\"B\")]), [#text(\"1\")], [#text(\"2\")])\n";
        assert_eq!(table_markup(&table), want);
    }

    /// Verifies long cell tokens gain zero-width break opportunities.
    #[test]
    fn test_cell_breaks_long_tokens() {
        let long = "a".repeat(40);
        let rendered = cell(&long);
        assert!(rendered.contains('\u{200b}'));
    }

    /// Verifies that the cover is emitted after the preamble.
    #[test]
    fn test_render_emits_cover() {
        let markup = render(&Document::new("T", "S"));
        assert!(markup.contains("#cover(\"T\", \"S\")"));
    }
}
