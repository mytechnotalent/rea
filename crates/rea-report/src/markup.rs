// Import crate::document
use crate::document::{Block, Document, Section, Table};

/// Page, typography, table, and cover styling shared by every report.
const PREAMBLE: &str = r##"#let accent = rgb("#1f3a5f")
#let muted = luma(110)
#set page(
  paper: "a4",
  margin: (x: 2cm, top: 2.4cm, bottom: 2.2cm),
  header: context if counter(page).get().first() > 1 {
    set text(8pt, fill: muted)
    [Reverse Engineering Assistant #h(1fr) Technical Analysis Report]
  },
  footer: context if counter(page).get().first() > 1 {
    set text(8pt, fill: muted)
    h(1fr)
    counter(page).display("1 / 1", both: true)
  },
)
#set text(font: "Libertinus Serif", size: 10.5pt, lang: "en")
#set par(justify: true, leading: 0.62em)
#set heading(numbering: "1.1")
#show heading: set text(fill: accent)
#show heading.where(level: 1): it => block(above: 1.6em, below: 0.9em, text(15pt, it))
#show raw: set text(font: "DejaVu Sans Mono", size: 7.5pt)
#show raw.where(block: true): it => block(
  fill: luma(246), inset: 8pt, radius: 3pt, width: 100%, it,
)
#set table(
  stroke: 0.4pt + luma(190),
  inset: (x: 5pt, y: 4pt),
  fill: (x, y) => if y == 0 { accent.lighten(85%) },
)
#show table: set par(justify: false)
#show table.cell: set text(size: 8.5pt)
#show table.cell.where(y: 0): strong
#let cover(title, subtitle) = {
  set par(justify: false)
  v(28%)
  text(10pt, fill: muted, tracking: 2pt)[REVERSE ENGINEERING REPORT]
  v(4pt)
  line(length: 100%, stroke: 1.5pt + accent)
  v(10pt)
  text(26pt, weight: "bold", fill: accent, title)
  v(6pt)
  text(12pt, subtitle)
  v(1fr)
  text(9pt, fill: muted)[Generated by Reverse Engineering Assistant]
  pagebreak()
  outline(depth: 2)
  pagebreak()
}
"##;

/// Renders a document as a complete Typst source file.
///
/// # Arguments
///
/// * `doc` - Document to render.
///
/// # Returns
///
/// Typst markup ready for compilation.
#[must_use]
pub fn render(doc: &Document) -> String {
    let (title, subtitle) = (string(&doc.title), string(&doc.subtitle));
    let head = format!("#set document(title: {title})\n#cover({title}, {subtitle})\n");
    let mut out = PREAMBLE.to_string() + &head;
    for section in &doc.sections {
        out.push_str(&section_markup(section));
    }
    out
}

/// Renders one section as a level-one heading followed by its blocks.
///
/// # Arguments
///
/// * `section` - Section to render.
///
/// # Returns
///
/// Typst markup for the section.
fn section_markup(section: &Section) -> String {
    let mut out = format!("= {}\n\n", text(&section.heading));
    for block in &section.blocks {
        out.push_str(&block_markup(block));
        out.push('\n');
    }
    out
}

/// Renders one block.
///
/// # Arguments
///
/// * `block` - Block to render.
///
/// # Returns
///
/// Typst markup for the block, ending in a newline.
fn block_markup(block: &Block) -> String {
    match block {
        Block::Paragraph(t) => format!("{}\n", text(t)),
        Block::Bullets(items) => items.iter().map(|i| bullet(i)).collect(),
        Block::Table(table) => table_markup(table),
        Block::Code(code) => format!("#raw(block: true, {})\n", string(code)),
        Block::Subheading(t) => format!("== {}\n", text(t)),
    }
}

/// Renders one bullet list item.
///
/// # Arguments
///
/// * `item` - Item text.
///
/// # Returns
///
/// A Typst list line.
fn bullet(item: &str) -> String {
    ["- ", &text(item), "\n"].concat()
}

/// Renders a table with a repeating header row.
///
/// # Arguments
///
/// * `table` - Table to render.
///
/// # Returns
///
/// A Typst `table` call.
fn table_markup(table: &Table) -> String {
    let header: Vec<String> = table.headers.iter().map(|h| cell(h)).collect();
    let body: Vec<String> = table.rows.iter().flatten().map(|c| cell(c)).collect();
    let (columns, header) = (table.headers.len().max(1), header.join(", "));
    let body = body.join(", ");
    format!("#table(columns: {columns}, table.header({header}), {body})\n")
}

/// Wraps text as one table cell.
///
/// # Arguments
///
/// * `raw` - Cell text.
///
/// # Returns
///
/// A Typst content block holding the text.
fn cell(raw: &str) -> String {
    format!("[{}]", text(raw))
}

/// Embeds arbitrary text in markup without interpreting any of it.
///
/// # Arguments
///
/// * `raw` - Untrusted text.
///
/// # Returns
///
/// A terminated `#"..."` string expression.
fn text(raw: &str) -> String {
    format!("#{};", string(raw))
}

/// Quotes text as a Typst string literal.
///
/// # Arguments
///
/// * `raw` - Untrusted text.
///
/// # Returns
///
/// A double-quoted literal with every special character escaped.
fn string(raw: &str) -> String {
    let body: String = raw.chars().map(escape).collect();
    format!("\"{body}\"")
}

/// Escapes one character for use inside a Typst string literal.
///
/// # Arguments
///
/// * `c` - Character to escape.
///
/// # Returns
///
/// The character itself or its escape sequence.
fn escape(c: char) -> String {
    match c {
        '\\' => "\\\\".to_string(),
        '"' => "\\\"".to_string(),
        '\n' => "\\n".to_string(),
        c if c.is_control() => format!("\\u{{{:x}}}", u32::from(c)),
        c => c.to_string(),
    }
}

#[cfg(test)]
mod tests {
    // Import all parent module items
    use super::*;

    /// Verifies that quotes, backslashes, and controls are escaped.
    #[test]
    fn test_string_escapes_specials() {
        assert_eq!(string("a\"b\\c\n\u{1}"), "\"a\\\"b\\\\c\\n\\u{1}\"");
    }

    /// Verifies that markup characters are inert inside text.
    #[test]
    fn test_text_wraps_markup_characters() {
        assert_eq!(text("*_#$"), "#\"*_#$\";");
    }

    /// Verifies table markup carries the column count and cells.
    #[test]
    fn test_table_markup_lists_cells() {
        let table = Table::new(&["A", "B"]).row(vec!["1".into(), "2".into()]);
        let want = "#table(columns: 2, table.header([#\"A\";], [#\"B\";]), [#\"1\";], [#\"2\";])\n";
        assert_eq!(table_markup(&table), want);
    }

    /// Verifies that the cover is emitted after the preamble.
    #[test]
    fn test_render_emits_cover() {
        let markup = render(&Document::new("T", "S"));
        assert!(markup.contains("#cover(\"T\", \"S\")"));
    }
}
